# Створюємо декоратор для приховування пароля
def hide_password(func):
    # Створюємо функцію, яка замінить результат
    def wrapper(*args, **kwargs):
        # Викликаємо початкову функцію
        func(*args, **kwargs)

        # Замість результату повертаємо 8 зірочок
        return "********"

    # Повертаємо функцію-обгортку
    return wrapper


# Застосовуємо декоратор до функції get_password
@hide_password
def get_password():
    # Просимо користувача ввести пароль
    password = input("Введіть пароль: ")

    # Повертаємо введений пароль
    return password


# Викликаємо функцію та записуємо результат у змінну
result = get_password()

# Виводимо прихований пароль на екран
print("Прихований пароль:", result)